import type { DemoProject, Product, Shop } from '../types';
import { resolveDishPhotoClient } from '../utils/dishPhotoResolver';

function makeProducts(
  shopId: string,
  items: Array<{
    id: string;
    name: string;
    category: string;
    price: number;
    description?: string;
    barcode?: string;
    imageUrl?: string;
    isOffer?: boolean;
    originalPrice?: number;
    offerLabel?: string;
  }>
): Product[] {
  return items.map((item, idx) => ({
    id: item.id,
    shopId,
    shopOwnerId: 'demo-owner',
    name: item.name,
    category: item.category,
    price: item.price,
    description: item.description || '',
    imageUrl: item.imageUrl || resolveDishPhotoClient(item.name, item.category),
    barcode: item.barcode || '',
    available: true,
    variants: [],
    sortOrder: idx,
    isOffer: Boolean(item.isOffer),
    originalPrice: item.originalPrice,
    offerLabel: item.offerLabel,
  }));
}

